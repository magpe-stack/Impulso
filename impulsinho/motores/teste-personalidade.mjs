import assert from 'node:assert/strict';
import {criarPersonalidade} from './motor-personalidade.mjs';
let t=0,s={},calls=[],aceita=true;
const p=criarPersonalidade({coordenador:{receber:async(e,o)=>{calls.push([e,o]);return aceita}},estado:()=>s,agora:()=>t,atalhos:[{texto:'Atalho validado',verificado:true},{texto:'Atalho falso'}]});
assert.equal(await p.receber('invalido'),false);
assert.equal(await p.receber('habito_concluido'),true);
const primeira=calls.at(-1)[1].mensagem;
assert.equal(await p.receber('habito_concluido'),true);
assert.notEqual(calls.at(-1)[1].mensagem,primeira);
aceita=false;assert.equal(await p.receber('habito_concluido'),false);const rejeitada=calls.at(-1)[1].mensagem;
aceita=true;await p.receber('habito_concluido');assert.equal(calls.at(-1)[1].mensagem,rejeitada);
s.foco=true;assert.equal(await p.receber('dica_exibida'),false);
s.foco=false;assert.equal(await p.verificar(),false);
s.espontaneo=true;t=900000;assert.equal(await p.verificar(),true);
assert.equal(await p.verificar(),false);
assert.equal(await p.receber('dica_exibida'),false);
s.silencio=true;assert.equal(await p.receber('habito_concluido'),false);
assert.equal(await p.receber('chefao_derrotado'),true);
s.silencio=false;s.visivel=false;assert.equal(await p.receber('chefao_derrotado'),false);
s.visivel=true;await p.receber('alerta_backup',{mensagem:'override'});assert.equal(calls.at(-1)[1].mensagem,undefined);
p.destruir();assert.equal(await p.receber('chefao_derrotado'),false);
