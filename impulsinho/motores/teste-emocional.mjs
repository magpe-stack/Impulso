import assert from 'node:assert/strict';
import {criarCoordenador,cenas} from './motor-emocional.mjs';
let face, texto, chamadas=[], permitido=false, tempo=0;
const c=criarCoordenador({motor:{mostrar:async e=>{chamadas.push(e);return false},limpar(){}},expressao:v=>face=v,balao:v=>texto=v,alertaPermitido:()=>permitido,agora:()=>tempo});
assert.equal(await c.receber('inexistente'),false);
assert.equal(await c.receber('alerta_backup'),false);
assert.equal(await c.receber('habito_concluido'),true);
assert.equal(face,'alegria'); assert.equal(texto,'Mais um hábito concluído!');
assert.equal(await c.receber('dica_exibida'),false);
assert.equal(await c.receber('chefao_derrotado'),true);
assert.equal(face,'celebracao');
c.limpar(); assert.equal(face,'neutra'); assert.equal(texto,'');
assert.equal(await c.receber('sessao_iniciada'),false);
tempo=9000; permitido=true; assert.equal(await c.receber('alerta_backup'),true);
assert.equal(chamadas.includes('alerta_backup'),false);
permitido=false;c.atualizarPreferencias();assert.equal(texto,'');
c.destruir();assert.equal(await c.receber('chefao_derrotado'),false);
